KEYCLOAK = os.environ.get("IDENTITY_DEMO_KEYCLOAK_URL", "http://127.0.0.1:18080").rstrip("/")
JIRA = "http://127.0.0.1:18081"
ISSUER = KEYCLOAK + "/realms/identity-demo"


class NoRedirect(HTTPRedirectHandler):
    """Keep authorization redirects visible without contacting a callback server."""

    def redirect_request(self, req: Any, fp: Any, code: int, msg: str,
                         headers: Any, newurl: str) -> None:
        """Return the redirect to the caller without following it."""
        return None


class LoginForm(HTMLParser):
    """Extract the standard Keycloak login action and hidden form inputs."""

    def __init__(self) -> None:
        super().__init__()
        self.action = ""
        self.fields: dict[str, str] = {}

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        """Read form attributes without rendering or executing HTML."""
        values = dict(attrs)
        if tag == "form" and values.get("id") == "kc-form-login":
            self.action = values.get("action") or ""
        if tag == "input" and values.get("type") == "hidden" and values.get("name"):
            self.fields[str(values["name"])] = values.get("value") or ""


def request(url: str, *, fields: dict | None = None, headers: dict | None = None,
            opener: Any = None) -> tuple[int, Any, bytes]:
    """Send a bounded request only to the local fixture tunnel."""
    parsed = urlparse(url)
    route_host = urlparse(KEYCLOAK).hostname
    allowed_hosts = {urlparse(active_profile().origin(service)).hostname
                     for service in ('fixture-keycloak', 'fixture-keycloak-upstream')}
    allowed_route = (parsed.scheme == "https" and parsed.hostname == route_host
                     and route_host in allowed_hosts and parsed.port in (None, 443)
                     and parsed.username is None and parsed.password is None)
    if parsed.hostname != "127.0.0.1" and not allowed_route:
        raise ValueError("Fixture tests refuse destinations outside our owned fixtures")
    data = urlencode(fields).encode() if fields is not None else None
    req = Request(url, data=data, headers=headers or {})
    client = opener or build_opener(NoRedirect())
    try:
        with client.open(req, timeout=20) as response:
            return response.status, response.headers, response.read(2_000_000)
    except HTTPError as error:
        return error.code, error.headers, error.read(2_000_000)


def login(username: str, password: str, *, client_id: str = "identity-demo-ui") -> dict:
    """Complete real Authorization Code + PKCE without password grants."""
    verifier = secrets.token_urlsafe(48)
    challenge = base64.urlsafe_b64encode(hashlib.sha256(verifier.encode()).digest()).rstrip(b"=").decode()
    state, nonce = secrets.token_urlsafe(24), secrets.token_urlsafe(24)
    client = build_opener(HTTPCookieProcessor(CookieJar()), NoRedirect())
    query = urlencode({"client_id": client_id, "response_type": "code",
        "scope": "openid", "redirect_uri": "http://127.0.0.1:18085/callback", "state": state,
        "nonce": nonce, "code_challenge": challenge, "code_challenge_method": "S256"})
    status, _, body = request(ISSUER + "/protocol/openid-connect/auth?" + query, opener=client)
    if status != 200:
        raise RuntimeError("Authorization endpoint did not present login")
    form = LoginForm()
    form.feed(body.decode())
    if not form.action:
        raise RuntimeError("Expected Keycloak login form missing")
    status, headers, body = request(form.action, fields={**form.fields, "username": username,
                                "password": password, "credentialId": ""}, opener=client)
    if status != 302:
        if status == 200 and any(message in body.decode() for message in (
                "Invalid username or password", "Invalid username or email")):
            raise PermissionError("User credentials rejected")
        raise RuntimeError("Unexpected login response; not credential-denial evidence")
    callback = headers.get("Location", "")
    if not callback.startswith("http://127.0.0.1:18085/callback?"):
        raise RuntimeError("Unexpected authorization redirect")
    parameters = parse_qs(urlparse(callback).query)
    if parameters.get("state") != [state] or "code" not in parameters:
        raise RuntimeError("Authorization state/code mismatch")
    status, _, body = request(ISSUER + "/protocol/openid-connect/token", fields={
        "grant_type": "authorization_code", "client_id": client_id,
        "redirect_uri": "http://127.0.0.1:18085/callback", "code": parameters["code"][0],
        "code_verifier": verifier})
    if status != 200:
        raise RuntimeError("Authorization-code exchange failed")
    return {**json.loads(body), "expected_nonce": nonce}


def verify(token: str, audience: str, issuer: str = ISSUER) -> dict:
    """Validate issuer, audience, expiry and signature using the standard JWT library."""
    status, _, body = request(ISSUER + "/protocol/openid-connect/certs")
    if status != 200:
        raise RuntimeError("Fixture JWKS unavailable")
    keys = jwt.PyJWKSet.from_dict(json.loads(body))
    key_id = jwt.get_unverified_header(token).get("kid")
    key = next(key.key for key in keys.keys if key.key_id == key_id)
    return jwt.decode(token, key, algorithms=["RS256"], audience=audience, issuer=issuer,
                      options={"require": ["exp", "iat", "sub", "aud", "iss"]})


