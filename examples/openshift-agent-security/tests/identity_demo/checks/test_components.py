"""Non-mutating tests against owned fixtures through localhost-only oc tunnels.

These component tests do not establish OpenShell, SPIRE, or gateway enforcement.
Set IDENTITY_DEMO_CREDENTIALS_FILE to the private file generated by the lab script.
"""

